###############################################################################
# summary_all.R
#
# Returns summary statistics for every variable in the model.
###############################################################################

summary_all <- function(deb_data){
  
  #---------------------------------------------------------------------------
  # Types
  #---------------------------------------------------------------------------
  
  types <- get_types()
  
  #---------------------------------------------------------------------------
  # Summary table
  #---------------------------------------------------------------------------
  
  summary_df <- data.frame()
  
  #---------------------------------------------------------------------------
  # Loop over types
  #---------------------------------------------------------------------------
  
  for(type in types){
    
    temp <- summary_type(
      deb_data = deb_data,
      type = type
    )
    
    summary_df <- rbind(
      summary_df,
      temp
    )
    
  }
  
  return(summary_df)
  
}